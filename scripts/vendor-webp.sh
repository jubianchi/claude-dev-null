#!/usr/bin/env bash
#
# Writes hooks/vendor/webp.js: the WebP decoder of ts-webp (MIT), at the commit below, bundled into one module the
# hooks module imports, since its own environment has no WebAssembly and no package manager. Its encoders are left
# out. Run it again, with another commit, to update the decoder.

set -euo pipefail

REPOSITORY=https://github.com/stacksjs/ts-webp
COMMIT=1c09b0a7680e0042a6658847775159b4ab9fc9fa
ESBUILD=esbuild@0.25.10

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SOURCE="$(mktemp -d)"
trap 'rm -rf "$SOURCE"' EXIT

git -C "$SOURCE" init -q
git -C "$SOURCE" fetch -q --depth 1 "$REPOSITORY" "$COMMIT"
git -C "$SOURCE" checkout -q FETCH_HEAD

BANNER="// Generated by scripts/vendor-webp.sh from $REPOSITORY at $COMMIT: do not edit.
// ts-webp, by Chris Breuer <chris@stacksjs.org>, under the MIT License: see hooks/vendor/webp.LICENSE."

# From the source, so that the paths esbuild writes above each module are its own, the same from one run to the next.
cd "$SOURCE"
npx --yes "$ESBUILD" src/decoder.ts \
  --bundle --format=esm --target=es2022 --legal-comments=none \
  --banner:js="$BANNER" \
  --outfile="$ROOT/hooks/vendor/webp.js"
